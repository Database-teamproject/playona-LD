import { ConfigService } from '@nestjs/config';
import { YouTubeClient } from './youtube.client';
import { AppleMusicClient } from './apple-music.client';
import { SpotifyClient } from './spotify.client';
import { GenieClient } from './genie.client';
import { MelonClient } from './melon.client';
import { FloClient } from './flo.client';

const config = new ConfigService({
  track: { youtube: { apiKey: 'test' }, spotify: { clientId: 'id', clientSecret: 'secret' } },
});
const response = (body: unknown) => new Response(JSON.stringify(body), { status: 200 });

describe('provider payloads', () => {
  afterEach(() => jest.restoreAllMocks());
  it('parses auto-generated YouTube audio and uses the recording release date', async () => {
    jest.spyOn(global, 'fetch').mockResolvedValue(
      response({
        items: [
          {
            id: 'abc',
            snippet: {
              title: 'Morning',
              channelTitle: 'Artist - Topic',
              categoryId: '10',
              description: 'Released on: 2026-01-01\nAuto-generated by YouTube.',
              publishedAt: '2026-02-01T00:00:00Z',
            },
            contentDetails: { duration: 'PT3M' },
          },
        ],
      }),
    );
    expect(await new YouTubeClient(config).getVideo('abc')).toMatchObject({
      title: 'Morning',
      artist: 'Artist',
      durationMs: 180000,
      releaseDate: '2026-01-01',
    });
  });
  it('rejects compilation and non-music YouTube sources', async () => {
    const fetcher = jest.spyOn(global, 'fetch');
    for (const snippet of [
      { title: 'Morning playlist', channelTitle: 'Artist - Topic', categoryId: '10' },
      { title: 'Morning', channelTitle: 'Artist - Topic', categoryId: '22' },
    ]) {
      fetcher.mockResolvedValueOnce(response({ items: [{ id: 'abc', snippet }] }));
      expect(await new YouTubeClient(config).getVideo('abc')).toBeNull();
    }
  });
  it('parses official artist videos without stripping recording version labels', async () => {
    jest.spyOn(global, 'fetch').mockResolvedValue(
      response({
        items: [
          {
            id: 'abc',
            snippet: {
              title: 'Artist - Morning (Live) (Official Video)',
              channelTitle: 'Artist Official',
              categoryId: '10',
            },
          },
        ],
      }),
    );
    expect(await new YouTubeClient(config).getVideo('abc')).toMatchObject({
      artist: 'Artist',
      title: 'Morning (Live)',
    });
  });
  it('skips an unrelated first Apple search result', async () => {
    jest.spyOn(global, 'fetch').mockResolvedValue(
      response({
        results: [
          { kind: 'song', trackId: 1, trackName: 'Other', artistName: 'Wrong' },
          { kind: 'song', trackId: 2, trackName: 'Morning', artistName: 'Artist' },
        ],
      }),
    );
    expect(await new AppleMusicClient().searchByText('Morning', 'Artist')).toMatchObject({
      externalId: '2',
    });
  });
  it('skips an unrelated first Spotify search result', async () => {
    jest
      .spyOn(global, 'fetch')
      .mockResolvedValueOnce(response({ access_token: 'test', expires_in: 3600 }))
      .mockResolvedValueOnce(
        response({
          tracks: {
            items: [
              { id: '1', name: 'Other', artists: [{ name: 'Wrong' }] },
              { id: '2', name: 'Morning', artists: [{ name: 'Artist' }] },
            ],
          },
        }),
      );
    expect(await new SpotifyClient(config).searchByText('Morning', 'Artist')).toMatchObject({
      externalId: '2',
    });
  });
  it('parses Genie and Melon OpenGraph metadata and FLO JSON', async () => {
    jest
      .spyOn(global, 'fetch')
      .mockResolvedValueOnce(
        new Response(
          '<meta property="og:title" content="Morning / Artist - genie"><span>재생시간</span><span>3:00</span>',
        ),
      )
      .mockResolvedValueOnce(
        new Response(
          '<meta property="og:title" content="Morning - Artist">발매일</dt><dd>2026.01.01</dd>',
        ),
      )
      .mockResolvedValueOnce(
        response({
          code: '2000000',
          data: {
            id: 1,
            name: 'Morning',
            artistList: [{ name: 'Artist' }],
            playTime: '03:00',
            album: { releaseYmd: '20260101' },
          },
        }),
      );
    expect(await new GenieClient().getTrack('1')).toMatchObject({
      title: 'Morning',
      artist: 'Artist',
      durationMs: 180000,
    });
    expect(await new MelonClient().getTrack('1')).toMatchObject({
      title: 'Morning',
      artist: 'Artist',
      releaseDate: '2026-01-01',
    });
    expect(await new FloClient().getTrack('1')).toMatchObject({
      title: 'Morning',
      artist: 'Artist',
      releaseDate: '2026-01-01',
      durationMs: 180000,
    });
  });
});
