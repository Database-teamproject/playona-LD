import { Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { TrackMetadata } from './track-metadata';
import { musicFetch } from './music-fetch';
import { decodeHtmlEntities } from './html-scrape.util';
import { hasMatchingArtist, isSimilar } from '../track-match-verifier';

interface YouTubeVideo {
  id: string;
  snippet: {
    title: string;
    channelTitle: string;
    description?: string;
    categoryId?: string;
    liveBroadcastContent?: string;
    publishedAt?: string;
    thumbnails?: Record<string, { url: string }>;
  };
  contentDetails?: { duration?: string };
}

@Injectable()
export class YouTubeClient {
  constructor(private readonly config: ConfigService) {}

  async getVideo(id: string): Promise<TrackMetadata | null> {
    return this.toMetadata((await this.getVideos([id]))[0]);
  }

  async searchTrack(title: string, artist: string): Promise<TrackMetadata | null> {
    return (
      (await this.searchCandidates({ title, artist })).find(
        (track) => isSimilar(title, track.title) && hasMatchingArtist(artist, track.artist),
      ) ?? null
    );
  }

  async searchCandidates({
    title,
    artist,
  }: Pick<TrackMetadata, 'title' | 'artist'>): Promise<TrackMetadata[]> {
    const res = await musicFetch(
      this.buildUrl('search', {
        q: title + ' ' + artist + ' topic',
        part: 'snippet',
        type: 'video',
        videoCategoryId: '10',
        maxResults: '10',
      }),
    );
    if (!res.ok) return [];
    const data = (await res.json()) as { items?: { id: { videoId: string } }[] };
    return (await this.getVideos((data.items ?? []).map((item) => item.id.videoId)))
      .map((video) => this.toMetadata(video))
      .filter((track): track is TrackMetadata => track !== null);
  }

  private async getVideos(ids: string[]): Promise<YouTubeVideo[]> {
    if (!ids.length) return [];
    const res = await musicFetch(
      this.buildUrl('videos', { id: ids.join(','), part: 'snippet,contentDetails' }),
    );
    return res.ok ? (((await res.json()) as { items?: YouTubeVideo[] }).items ?? []) : [];
  }

  private toMetadata(video?: YouTubeVideo): TrackMetadata | null {
    if (!video) return null;
    const s = video.snippet;
    if (
      !['10', '24'].includes(s.categoryId ?? '') ||
      (s.liveBroadcastContent && s.liveBroadcastContent !== 'none')
    )
      return null;
    const raw = decodeHtmlEntities(s.title),
      channel = decodeHtmlEntities(s.channelTitle);
    const description = s.description ?? '';
    if (
      /\b(playlist|compilation|medley|full\s+album|music\s+mix|cover|reaction|karaoke|sped|slowed)\b|플레이리스트|모음|메들리|커버/i.test(
        raw,
      )
    )
      return null;
    const topic = /- Topic$/.test(channel) || /Auto-generated by YouTube/i.test(description);
    let title = raw,
      artist = channel.replace(/\s*-\s*Topic$/, '').trim();
    if (!topic) {
      const cleaned = raw
        .replace(/\[(?:official[^\]]*|m\/?v|lyrics?)\]/gi, '')
        .replace(/\((?:official[^)]*|m\/?v|lyrics?)\)/gi, '')
        .replace(/\bOfficial\s+(?:Music\s+)?(?:Video|Audio|MV|Lyric\s+Video)\b/gi, '')
        .trim();
      const split = /^(.+?)\s+[-–—]\s+(.+)$/.exec(cleaned);
      if (!split) return null;
      artist = split[1].trim();
      title = split[2].trim().replace(/^['"]|['"]$/g, '');
      if (!hasMatchingArtist(artist, channel.replace(/\s*(?:official|vevo)\s*$/i, ''))) return null;
    }
    const thumbs = s.thumbnails ?? {};
    const released = /Released on:\s*(\d{4}-\d{2}-\d{2})/i.exec(description)?.[1];
    return {
      platformSlug: 'youtube-music',
      externalId: video.id,
      url: `https://music.youtube.com/watch?v=${video.id}`,
      isrc: null,
      title,
      artist,
      album: null,
      releaseDate: released ?? (topic ? null : (s.publishedAt?.slice(0, 10) ?? null)),
      durationMs: parseIsoDuration(video.contentDetails?.duration),
      thumbnailUrl: (thumbs.high ?? thumbs.medium ?? thumbs.default)?.url ?? null,
    };
  }

  private buildUrl(path: string, params: Record<string, string>): string {
    const key = this.config.get<string>('track.youtube.apiKey') ?? '';
    return `https://www.googleapis.com/youtube/v3/${path}?${new URLSearchParams({ ...params, key })}`;
  }
}

function parseIsoDuration(iso?: string): number | null {
  const m = /^PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?$/.exec(iso ?? '');
  return m ? ((Number(m[1] ?? 0) * 60 + Number(m[2] ?? 0)) * 60 + Number(m[3] ?? 0)) * 1000 : null;
}
